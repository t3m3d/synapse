#!/usr/bin/env bash
set -euo pipefail

workspace="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
firefox_root="${SYNAPSE_FIREFOX_ROOT:-$HOME/mozilla-source/firefox}"
build_root="$workspace/.synapse-build"
obj_root="$build_root/obj-synapse"
mozbuild_root="$build_root/mozbuild"

fail() {
  printf 'Synapse: %s\n' "$*" >&2
  exit 1
}

need_command() {
  command -v "$1" >/dev/null 2>&1 || fail "required command is missing: $1"
}

# macOS ships a Kerberos credential-cache tool named kcc in /usr/bin, which can
# shadow the Krypton compiler when /usr/local/bin is later in PATH. Resolve the
# compiler by its version banner instead of by name alone.
find_krypton_kcc() {
  local candidate
  for candidate in "${SYNAPSE_KCC:-}" "$(command -v kcc 2>/dev/null)" \
    /usr/local/bin/kcc /opt/homebrew/bin/kcc; do
    [[ -n "$candidate" && -x "$candidate" ]] || continue
    if "$candidate" --version 2>/dev/null | grep -q '^kcc version '; then
      printf '%s\n' "$candidate"
      return 0
    fi
  done
  return 1
}

check_roots() {
  [[ -f "$workspace/tools/synapse.ks" ]] || fail "workspace is not a Synapse repository: $workspace"
  [[ -f "$firefox_root/mach" ]] || fail "Firefox source is missing: $firefox_root"
  [[ "$workspace" != "$firefox_root" ]] || fail "Synapse and Firefox roots must be separate"
}

doctor() {
  local failures=0
  printf 'Workspace root: %s\n' "$workspace"
  printf 'Firefox root: %s\n' "$firefox_root"
  printf 'Host: macOS %s (%s)\n' "$(sw_vers -productVersion)" "$(uname -m)"

  for command in git rsync python3; do
    if command -v "$command" >/dev/null 2>&1; then
      printf '%s: ok\n' "$command"
    else
      printf '%s: missing\n' "$command"
      failures=$((failures + 1))
    fi
  done

  local kcc_path
  if kcc_path="$(find_krypton_kcc)"; then
    printf 'Krypton compiler: ok (%s, %s)\n' "$kcc_path" \
      "$("$kcc_path" --version 2>/dev/null | head -n 1)"
  else
    printf 'Krypton compiler: missing (install Krypton 2.4+ or set SYNAPSE_KCC)\n'
    failures=$((failures + 1))
  fi

  if [[ -f "$firefox_root/mach" ]]; then
    printf 'Firefox source: ok\n'
  else
    printf 'Firefox source: missing (%s)\n' "$firefox_root"
    failures=$((failures + 1))
  fi

  ((failures == 0)) || fail "$failures required check(s) failed"
  printf 'Doctor: ready\n'
}

install_mozconfig() {
  local template="$workspace/config/mozconfig.in"
  local target="$firefox_root/mozconfig"

  if [[ -f "$target" ]] && ! grep -q '^# Generated by Synapse' "$target"; then
    [[ -f "$target.pre-synapse" ]] || cp -p "$target" "$target.pre-synapse"
  fi

  sed \
    -e "s|@SYNAPSE_WORKSPACE_NATIVE@|$workspace|g" \
    -e "s|@SYNAPSE_WORKSPACE_MSYS@|$workspace|g" \
    "$template" >"$target"
  grep -q '@SYNAPSE_WORKSPACE_' "$target" && fail "mozconfig has unresolved placeholders"
  printf 'Installed Synapse mozconfig: %s\n' "$target"
}

apply_privacy_patch() {
  local patch="$workspace/overlay/privacy/privacy-loader.patch"
  if git -C "$firefox_root" apply --check "$patch" >/dev/null 2>&1; then
    git -C "$firefox_root" apply "$patch"
    printf 'Applied Synapse privacy loader patch.\n'
  elif git -C "$firefox_root" apply --reverse --check "$patch" >/dev/null 2>&1; then
    printf 'Synapse privacy loader patch is already applied.\n'
  else
    fail "privacy loader patch no longer applies cleanly"
  fi
}

apply_overlay() {
  check_roots
  need_command rsync
  printf 'Applying Synapse browser overlay without deleting upstream files...\n'
  rsync -a "$workspace/overlay/browser/" "$firefox_root/browser/"
  [[ -f "$firefox_root/browser/branding/synapse/configure.sh" ]] || fail "branding overlay verification failed"
  [[ -f "$firefox_root/browser/app/profile/synapse.js" ]] || fail "privacy preferences verification failed"
  apply_privacy_patch
  install_mozconfig
  printf 'Apply: complete\n'
}

run_mach() {
  local label="$1"
  shift
  doctor
  apply_overlay
  mkdir -p "$build_root" "$mozbuild_root"
  local log="$build_root/mach-$label.log"
  printf 'Running: mach %s\nSource root: %s\nLog: %s\n' "$*" "$firefox_root" "$log"
  # mach's Python bootstrap re-executes itself as a relative `mach` path, so it
  # must be started as ./mach from the Firefox source root.
  if ( cd "$firefox_root" && MOZBUILD_STATE_PATH="$mozbuild_root" ./mach "$@" >"$log" 2>&1 ); then
    printf 'Mach %s: complete\n' "$label"
  else
    tail -n 80 "$log" >&2 || true
    fail "mach $label failed"
  fi
}

run_core_tests() {
  local kcc_path
  kcc_path="$(find_krypton_kcc)" ||
    fail "Krypton compiler is missing (install Krypton 2.4+ or set SYNAPSE_KCC)"
  mkdir -p "$build_root"
  printf 'Krypton compiler: %s\n' "$kcc_path"
  "$kcc_path" "$workspace/tests/run.ks" -o "$build_root/synapse-tests"
  if ! "$build_root/synapse-tests"; then
    fail "Krypton core contracts failed"
  fi
}

build_i2p_settings() {
  local kcc_path
  kcc_path="$(find_krypton_kcc)" ||
    fail "Krypton compiler is missing (install Krypton 2.4+ or set SYNAPSE_KCC)"
  mkdir -p "$build_root"
  "$kcc_path" "$workspace/src/control/i2p_settings.ks" -o "$build_root/synapse-i2p-settings"
  printf 'Built I2P settings app: %s\n' "$build_root/synapse-i2p-settings"
}

i2p_settings() {
  build_i2p_settings
  SYNAPSE_WORKSPACE_ROOT="$workspace" "$build_root/synapse-i2p-settings"
}

i2p_identity() {
  case "${1:-personal}" in
    personal|work|school|creator|second-account) printf '%s\n' "${1:-personal}" ;;
    *) fail "unknown I2P identity: $1 (choose personal, work, school, creator, or second-account)" ;;
  esac
}

i2p_proxy_ready() {
  python3 -c 'import socket; s=socket.socket(); s.settimeout(1.5); rc=s.connect_ex(("127.0.0.1",4444)); s.close(); raise SystemExit(0 if rc == 0 else 1)' >/dev/null 2>&1
}

i2p_check() {
  printf 'I2P+ HTTP/HTTPS proxy: 127.0.0.1:4444\n'
  if i2p_proxy_ready; then
    printf 'I2P+ endpoint check: TCP listener available (not authenticated)\n'
  else
    printf 'I2P+ readiness: unavailable; start I2P+ and wait for its HTTP proxy\n' >&2
    return 1
  fi
}

i2p_setup_check() {
  local router_script
  if command -v java >/dev/null 2>&1 && java -version >/dev/null 2>&1; then
    printf 'Java runtime: available\n'
    java -version 2>&1 | head -n 1
  else
    printf 'Java runtime: missing (I2P+ universal installer requires Java 8 or later)\n'
  fi
  if router_script="$(i2p_router_script 2>/dev/null)"; then
    printf 'I2P+ router script: %s\n' "$router_script"
  else
    printf 'I2P+ router script: not found in /Applications/i2p or ~/i2p\n'
    printf 'For a custom install path, set SYNAPSE_I2P_ROUTER_DIR.\n'
  fi
  if i2p_proxy_ready; then
    printf 'I2P+ HTTP proxy: listening at 127.0.0.1:4444 (TCP only; bootstrap not verified)\n'
  else
    printf 'I2P+ HTTP proxy: not listening at 127.0.0.1:4444\n'
  fi
}

i2p_install_guide() {
  open "https://i2pplus.github.io/download.html"
  printf 'Opened the official I2P+ downloads page. Install Java 8+ first if needed.\n'
}

i2p_router_script() {
  local router_dir
  if [[ -n "${SYNAPSE_I2P_ROUTER_DIR:-}" ]]; then
    router_dir="$SYNAPSE_I2P_ROUTER_DIR"
    [[ -f "$router_dir/i2prouter" ]] || fail "I2P+ router script not found in SYNAPSE_I2P_ROUTER_DIR: $router_dir"
    printf '%s\n' "$router_dir/i2prouter"
    return 0
  fi

  for router_dir in /Applications/i2p "$HOME/i2p"; do
    if [[ -f "$router_dir/i2prouter" ]]; then
      printf '%s\n' "$router_dir/i2prouter"
      return 0
    fi
  done
  fail "I2P+ installation not found; set SYNAPSE_I2P_ROUTER_DIR to its install directory"
}

i2p_router_status() {
  local router_script router_dir status_rc
  router_script="$(i2p_router_script)"
  router_dir="$(dirname "$router_script")"
  printf 'I2P+ router command status:\n'
  (cd "$router_dir" && sh ./i2prouter status) || status_rc=$?
  status_rc="${status_rc:-0}"
  if i2p_proxy_ready; then
    printf 'Proxy endpoint: listening at 127.0.0.1:4444 (TCP only; bootstrap not verified)\n'
  else
    printf 'Proxy endpoint: not listening at 127.0.0.1:4444\n'
  fi
  return "$status_rc"
}

i2p_router_start() {
  local router_script router_dir
  router_script="$(i2p_router_script)"
  router_dir="$(dirname "$router_script")"
  if i2p_proxy_ready; then
    printf 'I2P+ proxy is already listening at 127.0.0.1:4444\n'
    return 0
  fi
  (cd "$router_dir" && sh ./i2prouter start) || fail "I2P+ router start command failed"
  printf 'I2P+ start requested. Synapse I2P browsing remains blocked until the proxy listens at 127.0.0.1:4444.\n'
}

i2p_router_stop() {
  local router_script router_dir
  router_script="$(i2p_router_script)"
  router_dir="$(dirname "$router_script")"
  (cd "$router_dir" && sh ./i2prouter graceful) || fail "I2P+ graceful shutdown command failed"
  printf 'I2P+ graceful shutdown requested.\n'
}

