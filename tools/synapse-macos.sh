write_i2p_profile_prefs() {
  local profile="$1"
  local target="$profile/user.js"
  local staged
  if [[ -e "$target" ]] && ! grep -Fq '// Generated by Synapse. Dedicated I2P+ profile.' "$target"; then
    fail "refusing to replace a user-owned I2P profile preference file: $target"
  fi
  if [[ -e "$target" ]]; then
    local existing staged_content
    existing="$(cat "$target")"
    staged="$(mktemp "$profile/.user.js.XXXXXX")"
    chmod 600 "$staged"
    write_i2p_prefs_to "$staged"
    staged_content="$(cat "$staged")"
    if [[ "$existing" == "$staged_content" ]]; then
      rm -f "$staged"
      return 0
    fi
    mv -f "$staged" "$target"
    return 0
  fi
  staged="$(mktemp "$profile/.user.js.XXXXXX")"
  chmod 600 "$staged"
  write_i2p_prefs_to "$staged"
  mv -f "$staged" "$target"
}

i2p_open() {
  local identity destination profile app start_url
  identity="$(i2p_identity "${1:-personal}")"
  destination="${2:-home}"
  case "$destination" in
    home) start_url="http://127.0.0.1:7657" ;;
    subscriptions) start_url="http://127.0.0.1:7657/susidns/subscriptions" ;;
    *) fail "unknown I2P destination: $destination (choose home or subscriptions)" ;;
  esac
  i2p_check || return 1

  app="$obj_root/dist/Synapse.app"
  [[ -d "$app" && -x "$app/Contents/MacOS/synapse" ]] ||
    fail "Synapse macOS app is missing; run tools/synapse-macos.sh build first"

  profile="$HOME/Library/Application Support/Synapse/Profiles/synapse-i2p-$identity"
  mkdir -p "$profile"
  chmod 700 "$profile"
  write_i2p_profile_prefs "$profile"

  printf 'Launching I2P %s with its isolated profile: %s\n' "$identity" "$profile"
  open -n "$app" --args -no-remote -profile "$profile" "$start_url"
}

usage() {
  cat <<'EOF'
Synapse macOS controller
  tools/synapse-macos.sh doctor
  tools/synapse-macos.sh i2p-settings
  tools/synapse-macos.sh i2p-check
  tools/synapse-macos.sh i2p-setup-check
  tools/synapse-macos.sh i2p-install-guide
  tools/synapse-macos.sh i2p-router-status
  tools/synapse-macos.sh i2p-router-start
  tools/synapse-macos.sh i2p-router-stop
  tools/synapse-macos.sh i2p-open [personal|work|school|creator|second-account] [home|subscriptions]
  tools/synapse-macos.sh apply
  tools/synapse-macos.sh build
  tools/synapse-macos.sh faster
  tools/synapse-macos.sh run
  tools/synapse-macos.sh package
  tools/synapse-macos.sh test-extension
  tools/synapse-macos.sh test-core

Optional environment:
  SYNAPSE_FIREFOX_ROOT  Firefox source checkout (default: ~/mozilla-source/firefox)
  SYNAPSE_I2P_ROUTER_DIR I2P+ install directory (default: /Applications/i2p or ~/i2p)
  SYNAPSE_KCC           Krypton compiler binary (default: first kcc reporting a
                        Krypton version; /usr/bin/kcc is macOS Kerberos)
EOF
}

command_name="${1:-}"
case "$command_name" in
  doctor) doctor ;;
  i2p-settings) i2p_settings ;;
  apply) apply_overlay ;;
  build) run_mach build build ;;
  faster) run_mach faster build faster ;;
  run) run_mach run run --no-remote ;;
  i2p-check) i2p_check ;;
  i2p-setup-check) i2p_setup_check ;;
  i2p-install-guide) i2p_install_guide ;;
  i2p-router-status) i2p_router_status ;;
  i2p-router-start) i2p_router_start ;;
  i2p-router-stop) i2p_router_stop ;;
  i2p-open) i2p_open "${2:-personal}" "${3:-home}" ;;
  package) run_mach package package ;;
  test-extension)
    run_mach test-extension test \
      browser/components/extensions/test/browser/browser_ext_browserAction_simple.js \
      --setpref dom.security.https_only_mode=false \
      --setpref dom.security.https_only_mode_pbm=false \
      --setpref network.lna.enabled=false \
      --setpref network.lna.blocking=false
    ;;
  test-core) run_core_tests ;;
  -h|--help|"") usage ;;
  *) usage >&2; fail "unknown command: $command_name" ;;
esac
